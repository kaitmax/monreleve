function scrubbed(extra = {}) {
  return {
    ...Object.fromEntries(Object.entries(process.env).filter(([name]) => !SECRETS.includes(name))),
    ...extra,
  };
}

/**
 * Whether a Docker daemon will answer.
 *
 * ASKED OF THE DAEMON, NOT OF THE BINARY. `docker` on PATH with no daemon
 * behind it exits non-zero on the first real command, which would turn a
 * missing daemon into a gate failure rather than a named skip.
 */
function dockerAvailable() {
  try {
    execFileSync('docker', ['version', '--format', '{{.Server.APIVersion}}'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
      timeout: 30_000,
    });

    return true;
  } catch {
    return false;
  }
}

function run(label, command, args, cwd, expect, env) {
  process.stdout.write(`--- ${label} ---\n`);

  const child = spawnSync(command, args, {
    cwd,
    encoding: 'utf8',
    shell: true,
    env: env ?? scrubbed(),
    maxBuffer: 64 * 1024 * 1024,
  });

  const output = `${child.stdout ?? ''}${child.stderr ?? ''}`;

  process.stdout.write(`${output.split('\n').slice(-14).join('\n')}\n`);

  if (child.status !== 0) {
    return { ok: false, why: `${label} exited ${String(child.status)}`, output };
  }

  // FW32, AC2: THE SILENCE. `expect` is tested against STRIPPED output, not
  // `output` itself. vitest's own summary line splits "Test Files" from its
  // digits with colour codes - `Test Files\x1b[22m \x1b[1m\x1b[32m164
  // passed...` - which \s+ does not bridge, so a run that had just PASSED
  // 2907/2907 read as silence and failed this exact check, deterministically,
  // on every fresh clone this task tried. NOT an environment or resource
  // defect (R265's own hypothesis, tested first and disproved: it reproduced
  // identically with 17 GB free as with 8.5 GB) - REPORT-FW31.txt's own
  // PUSH PROOF already named "one in gate-clone" among nine colour-fragile
  // patterns and closed only container-e2e.mjs's instance. This is that
  // instance. Imported rather than copied (R206) - stripAnsi is exactly the
  // function FW31 wrote and exported for reuse.
  if (!expect.test(stripAnsi(output))) {
    return {
      ok: false,
      why:
        `${label} exited 0 but printed nothing matching ${String(expect)}. ` +
        'A step that reports nothing must not read as a pass (R133).',
      output,
    };
  }

  return { ok: true, output };
}

function git(args, cwd = repo) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 }).trim();
}

/** DATABASE_URL out of web/.env, for the host only. Absent file is fine. */
function fromEnvFile() {
  try {
    const text = readFileSync(join(web, '.env'), 'utf8');
    const line = text.split('\n').find((row) => row.trimStart().startsWith('DATABASE_URL'));

    if (line === undefined) {
      return undefined;
    }

    const value = line.slice(line.indexOf('=') + 1).trim();

    return value.replace(/^["']|["']$/g, '');
  } catch {
    return undefined;
  }
}

/**
 * Where a local PostgreSQL is, taken from the developer's own DATABASE_URL.
 *
 * THOSE CREDENTIALS ARE NOT A SECRET - web/.env.example publishes them, and
 * they belong to a container docker-compose starts. What is read here is the
 * HOST, not a password worth protecting: the clone gets a database this script
 * creates and migrates, never the developer's.
 */
function postgres() {
  // IT READS web/.env WHEN THE SHELL HAS NOTHING, and the first run of this
  // script is why. Every database command in this repository is invoked as
  // `node --env-file-if-exists=.env ...`, so DATABASE_URL lives in that file
  // and NOT in the ambient environment - and the first gate:clone therefore
  // skipped the database suites while reporting a pass, on the very commits
  // whose database work it existed to settle. The skip was named, which is
  // the only reason it was noticed rather than believed.
  //
  // THIS IS NOT THE CLONE GETTING A .env. The clone never sees this file.
  // What is taken from it is WHERE PostgreSQL is listening; what the clone is
  // handed is a connection string to a scratch database created below, and
  // nothing else.
  const url = process.env.DATABASE_URL ?? fromEnvFile();

  if (url === undefined || url === '') {
    return null;
  }

  const parsed = new URL(url);
  const host = parsed.hostname;

  if (host !== 'localhost' && host !== '127.0.0.1' && host !== '::1') {
    return null;
  }

  return parsed;
}

const clone = mkdtempSync(join(tmpdir(), 'monreleve-clone-'));
let scratchDatabase = null;

/** Whether the production-write suite actually ran, so the summary can say so. */
let wroteInProduction = false;
let admin = null;

async function dropScratch() {
  if (scratchDatabase === null || admin === null) {
    return;
  }

  const { Client } = await import('pg');
  const client = new Client({ connectionString: admin.toString() });

  await client.connect();
  await client.query(`DROP DATABASE IF EXISTS "${scratchDatabase}" WITH (FORCE)`);
  await client.end();
}

/**
 * ONE CLEANUP PATH, called from the normal `finally` below AND from a signal
 * handler. Both `rmSync` (force: true) and `dropScratch` (IF EXISTS) are
 * idempotent, so calling this twice in a race is harmless.
 */
async function cleanup() {
  await dropScratch();
  rmSync(clone, { recursive: true, force: true });
}

/**
 * THE LEAK'S FIRST CAUSE (FW32, AC1): every step failure below used to call
 * process.exit(1) from inside the try block that follows. process.exit()
 * terminates immediately WITHOUT unwinding to a pending `finally` - a
 * documented Node.js semantic, not a bug in this file - so every failed run
 * leaked its clone (and, from one path, its scratch database). Failures now
 * `throw` instead, so the `finally` below runs on every exit from the try
 * block, success or failure alike.
 */
class GateCloneFailure extends Error {}

/**
 * THE LEAK'S SECOND, ORIGINAL CAUSE (AN1's nine killed-process leaks) IS
 * SEPARATE FROM THE ONE ABOVE, and this does not close it - it narrows what
 * remains open. A registered SIGINT/SIGTERM handler replaces Node's default
 * disposition for that signal, so without one, killing this process (a
 * terminal Ctrl+C, a supervisor's SIGTERM, `docker stop`) skipped this
 * file's cleanup entirely, exactly like the process.exit(1) paths did.
 *
 * WHAT THIS DOES NOT CLOSE, MEASURED RATHER THAN ASSUMED (see
 * REPORT-FW32.txt, THE LEAK): a SIGKILL cannot be caught by any process, by
 * definition. Narrower and less obvious, and measured against this file
 * itself rather than a throwaway probe - on THIS Windows machine, THREE
 * independent kill mechanisms were tried against a running `gate:clone`
 * with this exact handler registered, and NONE of them reached it (no
 * "received SIGTERM" line, no orderly exit code, and the clone leaked every
 * time): this harness's own foreground-timeout kill; a cross-process
 * `process.kill(pid, 'SIGINT')` from an unrelated node invocation (EPERM,
 * yet the target still died); and `kill -TERM <pid>` from the SAME Git Bash
 * shell that spawned it, tested twice, once mid-install and once well into
 * a long-running step - both times the child died, the parent logged one
 * more line and then stopped, and the temp clone remained. Node's Windows
 * SIGTERM is a libuv emulation over TerminateProcess, not a real signal a
 * handler can intercept, and this suggests the emulation does not wait for
 * a same-process synchronous throw/catch/finally already in flight to
 * finish before tearing the process down. NOT TESTED: a genuine interactive
 * terminal Ctrl+C, which Node's own docs describe as the supported case on
 * Windows - this session has no interactive terminal to produce one. So
 * this handler is written correctly and should do what it says under a real
 * POSIX SIGTERM/SIGINT (Linux CI, macOS, `docker stop`) - and, on this
 * machine, against every external kill mechanism actually tested, it did
 * not close the leak it was written for.
 */
let cleaningUp = false;

async function onSignal(signal, code) {
  if (cleaningUp) {
    return;
  }

  cleaningUp = true;
  console.error(`\ngate:clone: received ${signal}, cleaning up before exit`);
  await cleanup();
  process.exit(code);
}

process.on('SIGINT', () => {
  void onSignal('SIGINT', 130);
});
process.on('SIGTERM', () => {
  void onSignal('SIGTERM', 143);
});

