//
// RULING R199: does this work on a machine that is not mine?
//
// IT REPLACES gate:clean (R139), WHICH ANSWERED A WEAKER QUESTION. gate:clean
// copied `git ls-files` plus untracked-but-not-ignored files into a temp
// directory and ran install, typecheck and build there. That was the right
// idea and two steps short of the claim:
//
//   IT COPIED UNCOMMITTED WORK. Deliberately - it ran before a COMMIT, so the
//   code about to be committed had to be in the tree. gate:clone runs before a
//   PUSH, which is the unit that leaves this machine, so it clones HEAD. Work
//   that is not committed is not in the clone, and that is the point: a push
//   publishes commits, not a working directory.
//
//   IT STOPPED AT build. No tests, no size, no database - so a generated
//   Prisma client missing on a fresh install was caught, and a database suite
//   that only passes against a database somebody migrated by hand was not.
//
// WHY THE CLAIM NEEDS A HOME AT ALL. The GitHub Actions allowance for
// September 2026 is exhausted and CI returns on 1 October (R201). What CI was
// providing was never "the tests pass" - the local gate proves that. It was
// the answer to a different question, and FOUR DEFECTS THIS MONTH CAME FROM
// THAT GAP ALONE: web/public missing on a fresh checkout, a stale .next making
// `pnpm size` report fifteen times over budget, an orphaned server serving a
// build whose CSS had been replaced, and a generated Prisma client that
// existed locally and not on a runner.
//
// A CLONE, NOT A SCRUB, and that is the whole design. The obvious
// implementation moves .env aside and deletes node_modules, which mutates the
// working tree - R131 territory, needing a lock, and leaving a repository in
// pieces if it is interrupted. `git clone` gives a tree with .env,
// node_modules, .next and public/fonts absent BY CONSTRUCTION rather than by a
// scrub list somebody has to maintain. A scrub list falls behind; a clone
// cannot.
//
// NOTHING IS GENERATED BY THIS SCRIPT, AND THAT IS DELIBERATE. R199 asks for
// "prisma generate, fonts, tokens - and if a generation step is missing, the
// chain fails there, which is the point". So the chain calls the PROJECT'S own
// mechanisms and nothing else: `postinstall` must generate the Prisma client,
// `build` must copy the fonts. A script that generated them itself would prove
// the script works and hide that the project does not - which is exactly the
// FW14 defect, one layer up. R154: a mechanism is proven to deliver.
//
// R133: EVERY STEP ASSERTS A POSITIVE SIGNAL. A step that exits 0 having
// printed nothing recognisable is a failure here, not a silence read as
// success.
//
// AND EVERY STEP THAT CANNOT RUN IS NAMED, never silently omitted. A harness
// that quietly drops the browser suites reports the same green as one that
// ran them.

