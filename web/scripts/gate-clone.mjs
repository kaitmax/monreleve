// web/scripts/gate-clone.mjs
//
// RULING R199: does this work on a machine that is not mine?
//
// IT REPLACES gate:clean (R139), WHICH ANSWERED A WEAKER QUESTION. gate:clean
// copied `git ls-files` plus untracked-but-not-ignored files into a temp
// directory and ran install, typecheck and build there. That was the right
// idea and two steps short of the claim:
//
//   IT COPIED UNCOMMITTED WORK. Deliberately - it ran before a COMMIT, so the
//   code about to be committed had to be in the tree. gate:clone runs before a
//   PUSH, which is the unit that leaves this machine, so it clones HEAD. Work
//   that is not committed is not in the clone, and that is the point: a push
//   publishes commits, not a working directory.
//
//   IT STOPPED AT build. No tests, no size, no database - so a generated
//   Prisma client missing on a fresh install was caught, and a database suite
//   that only passes against a database somebody migrated by hand was not.
//
// WHY THE CLAIM NEEDS A HOME AT ALL. The GitHub Actions allowance for
// September 2026 is exhausted and CI returns on 1 October (R201). What CI was
// providing was never "the tests pass" - the local gate proves that. It was
// the answer to a different question, and FOUR DEFECTS THIS MONTH CAME FROM
// THAT GAP ALONE: web/public missing on a fresh checkout, a stale .next making
// `pnpm size` report fifteen times over budget, an orphaned server serving a
// build whose CSS had been replaced, and a generated Prisma client that
// existed locally and not on a runner.
//
// A CLONE, NOT A SCRUB, and that is the whole design. The obvious
// implementation moves .env aside and deletes node_modules, which mutates the
// working tree - R131 territory, needing a lock, and leaving a repository in
// pieces if it is interrupted. `git clone` gives a tree with .env,
// node_modules, .next and public/fonts absent BY CONSTRUCTION rather than by a
// scrub list somebody has to maintain. A scrub list falls behind; a clone
// cannot.
//
// NOTHING IS GENERATED BY THIS SCRIPT, AND THAT IS DELIBERATE. R199 asks for
// "prisma generate, fonts, tokens - and if a generation step is missing, the
// chain fails there, which is the point". So the chain calls the PROJECT'S own
// mechanisms and nothing else: `postinstall` must generate the Prisma client,
// `build` must copy the fonts. A script that generated them itself would prove
// the script works and hide that the project does not - which is exactly the
// FW14 defect, one layer up. R154: a mechanism is proven to deliver.
//
// R133: EVERY STEP ASSERTS A POSITIVE SIGNAL. A step that exits 0 having
// printed nothing recognisable is a failure here, not a silence read as
// success.
//
// AND EVERY STEP THAT CANNOT RUN IS NAMED, never silently omitted. A harness
// that quietly drops the browser suites reports the same green as one that
// ran them.

import { ciReadiness, describeReadiness } from './ci-readiness.mjs';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repo = resolve(web, '..');

/**
 * Environment variables a clean checkout does not have.
 *
 * DATABASE_URL IS IN THIS LIST AND IS ALSO HANDED BACK, to one step only.
 * The build must work WITHOUT it - that is FW14's ef629d5, where `next build`
 * imported every route module to collect page data and the Prisma client was
 * constructed at module scope. The database suites obviously need one. So the
 * chain below scrubs it everywhere and gives `test:db` a connection to a
 * database this script creates, which is a different claim from "the developer
 * happens to have one migrated".
 */
const SECRETS = [
  'DATABASE_URL',
  'RESEND_API_KEY',
  'NEXT_PUBLIC_SITE_URL',
  'FRONTALIER_RUNTIME',
  'FRONTALIER_DEV_ROUTES',
  'AUTH_SECRET',
  'ANDROID_PACKAGE_NAME',
  'ANDROID_SHA256_CERT_FINGERPRINTS',
];

/**
 * Steps that cannot run inside a fresh clone, each with the reason.
 *
 * NAMED RATHER THAN OMITTED. This list is printed on every run, pass or fail,
 * so "the browser suites did not run" is a line in the output instead of an
 * absence somebody has to notice.
 */
const CANNOT_RUN_HERE = [
  ['test:e2e', 'needs a Playwright browser download; runs locally via pnpm test:e2e'],
  ['test:visual', 'needs the Playwright Docker container (R98); runs locally via pnpm test:visual'],
  ['test:runtime', 'needs a Playwright browser download'],
  ['lighthouse', 'needs a Chrome binary and a served build'],
  ['parity:check', 'covered by typecheck here; the Node matrix is R201 workflow_dispatch from October'],
];

function scrubbed(extra = {}) {
  return {
    ...Object.fromEntries(Object.entries(process.env).filter(([name]) => !SECRETS.includes(name))),
    ...extra,
  };
}

function run(label, command, args, cwd, expect, env) {
  process.stdout.write(`--- ${label} ---\n`);

  const child = spawnSync(command, args, {
    cwd,
    encoding: 'utf8',
    shell: true,
    env: env ?? scrubbed(),
    maxBuffer: 64 * 1024 * 1024,
  });

  const output = `${child.stdout ?? ''}${child.stderr ?? ''}`;

  process.stdout.write(`${output.split('\n').slice(-14).join('\n')}\n`);

  if (child.status !== 0) {
    return { ok: false, why: `${label} exited ${String(child.status)}`, output };
  }

  if (!expect.test(output)) {
    return {
      ok: false,
      why:
        `${label} exited 0 but printed nothing matching ${String(expect)}. ` +
        'A step that reports nothing must not read as a pass (R133).',
      output,
    };
  }

  return { ok: true, output };
}

function git(args, cwd = repo) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 }).trim();
}

/** DATABASE_URL out of web/.env, for the host only. Absent file is fine. */
function fromEnvFile() {
  try {
    const text = readFileSync(join(web, '.env'), 'utf8');
    const line = text.split('\n').find((row) => row.trimStart().startsWith('DATABASE_URL'));

    if (line === undefined) {
      return undefined;
    }

    const value = line.slice(line.indexOf('=') + 1).trim();

    return value.replace(/^["']|["']$/g, '');
  } catch {
    return undefined;
  }
}

/**
 * Where a local PostgreSQL is, taken from the developer's own DATABASE_URL.
 *
 * THOSE CREDENTIALS ARE NOT A SECRET - web/.env.example publishes them, and
 * they belong to a container docker-compose starts. What is read here is the
 * HOST, not a password worth protecting: the clone gets a database this script
 * creates and migrates, never the developer's.
 */
function postgres() {
  // IT READS web/.env WHEN THE SHELL HAS NOTHING, and the first run of this
  // script is why. Every database command in this repository is invoked as
  // `node --env-file-if-exists=.env ...`, so DATABASE_URL lives in that file
  // and NOT in the ambient environment - and the first gate:clone therefore
  // skipped the database suites while reporting a pass, on the very commits
  // whose database work it existed to settle. The skip was named, which is
  // the only reason it was noticed rather than believed.
  //
  // THIS IS NOT THE CLONE GETTING A .env. The clone never sees this file.
  // What is taken from it is WHERE PostgreSQL is listening; what the clone is
  // handed is a connection string to a scratch database created below, and
  // nothing else.
  const url = process.env.DATABASE_URL ?? fromEnvFile();

  if (url === undefined || url === '') {
    return null;
  }

  const parsed = new URL(url);
  const host = parsed.hostname;

  if (host !== 'localhost' && host !== '127.0.0.1' && host !== '::1') {
    return null;
  }

  return parsed;
}

const clone = mkdtempSync(join(tmpdir(), 'monreleve-clone-'));
let scratchDatabase = null;
let admin = null;

async function dropScratch() {
  if (scratchDatabase === null || admin === null) {
    return;
  }

  const { Client } = await import('pg');
  const client = new Client({ connectionString: admin.toString() });

  await client.connect();
  await client.query(`DROP DATABASE IF EXISTS "${scratchDatabase}" WITH (FORCE)`);
  await client.end();
}

try {
  const head = git(['rev-parse', 'HEAD']);
  const subject = git(['log', '-1', '--pretty=%s']);
  const branch = git(['rev-parse', '--abbrev-ref', 'HEAD']);
  const dirty = git(['status', '--porcelain']);

  console.log('gate:clone - what is being checked');
  console.log(`  commit    ${head}`);
  console.log(`  subject   ${subject}`);
  console.log(`  branch    ${branch}`);

  // R184's shape: print what was photographed, not only what came out. A dirty
  // tree is not a failure - the clone is of HEAD and that is correct - but it
  // means uncommitted work is NOT in this run, and somebody reading a green
  // result needs to know that before they read it as covering their edits.
  if (dirty === '') {
    console.log('  tree      clean - HEAD is everything you have');
  } else {
    const count = dirty.split('\n').length;

    console.log(`  tree      DIRTY, ${count} path(s) NOT in this run:`);
    for (const line of dirty.split('\n').slice(0, 12)) {
      console.log(`              ${line}`);
    }
    console.log('            gate:clone clones HEAD. Commit before trusting this');
    console.log('            run as covering the work above.');
  }

  console.log(`  clone     ${clone}`);
  console.log(`  scrubbed  ${SECRETS.join(', ')}`);
  console.log('');
  console.log('  named as unable to run in a clone (R133 - not silently omitted):');
  for (const [step, why] of CANNOT_RUN_HERE) {
    console.log(`    ${step.padEnd(12)} ${why}`);
  }
  console.log('');

  execFileSync('git', ['clone', '--local', '--no-hardlinks', repo, clone], {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });

  const cloned = git(['rev-parse', 'HEAD'], clone);

  if (cloned !== head) {
    console.error(`gate:clone FAILED: the clone is at ${cloned}, this tree is at ${head}.`);
    process.exit(1);
  }

  const there = join(clone, 'web');

  // THE CHAIN. Ordered cheapest-signal-first, with build before size because
  // size reads .next, and the database last because it is the only step that
  // is handed a connection string.
  const steps = [
    [
      'pnpm install --frozen-lockfile',
      'pnpm',
      ['install', '--frozen-lockfile'],
      // The postinstall IS the assertion. If it stops generating the Prisma
      // client, typecheck fails two steps later with "no exported member
      // 'PrismaClient'" - which is FW14's da65dfa, reproduced.
      /Done in|Already up to date|packages/i,
    ],
    ['pnpm typecheck', 'pnpm', ['typecheck'], /tsc --noEmit/],
    ['pnpm lint', 'pnpm', ['lint'], /eslint \./],
    ['pnpm test', 'pnpm', ['test'], /Test Files\s+\d+ passed/],
    // `build` runs copy-fonts first, so public/fonts - which is gitignored and
    // therefore absent from the clone - has to be produced here or the build
    // fails. That is the "web/public missing on a fresh checkout" defect.
    ['pnpm build', 'pnpm', ['build'], /Compiled successfully|Generating static pages/],
    // The exact sentence check-budgets.mjs prints when both gates pass. A
    // looser pattern - /budget/i, say - would match the script's own
    // explanatory output and turn a failed measurement into a pass, which is
    // the failure mode R133 exists to stop rather than an example of it.
    ['pnpm size', 'pnpm', ['size'], /All gated routes pass both gates/],
  ];

  for (const [label, command, args, expect] of steps) {
    const result = run(label, command, args, there, expect);

    if (!result.ok) {
      console.error('');
      console.error(`GATE:CLONE FAILED - ${result.why}`);
      console.error('');
      console.error('This is a defect a normal gate cannot see: it passes on a machine');
      console.error('that has a .env, a generated client, a populated public/ or a');
      console.error('node_modules nobody rebuilt. A fresh clone has none of those.');
      process.exit(1);
    }
  }

  // ---------------------------------------------------------------------
  // THE DATABASE SUITES, against a database this script creates.
  //
  // Running them against the developer's own database would prove that the
  // suites pass where somebody has already migrated by hand - which is the
  // claim gate:clone exists to stop making. A scratch database created here,
  // migrated by the clone's own `db:deploy`, is the clean-machine claim for
  // the schema as well as for the build.
  // ---------------------------------------------------------------------
  const local = postgres();

  if (local === null) {
    console.log('');
    console.log('--- database suites: SKIPPED, and named ---');
    console.log('  DATABASE_URL is unset or does not point at a local host, so there');
    console.log('  is no PostgreSQL to create a scratch database on.');
    console.log('  `docker compose up -d` starts the one web/.env.example points at.');
    console.log('  THIS RUN DOES NOT COVER prisma/**, lib/db/** or tests/db/**.');
  } else {
    scratchDatabase = `monreleve_gate_clone_${head.slice(0, 8)}`;
    admin = local;

    const { Client } = await import('pg');
    const client = new Client({ connectionString: admin.toString() });

    await client.connect();
    await client.query(`DROP DATABASE IF EXISTS "${scratchDatabase}" WITH (FORCE)`);
    await client.query(`CREATE DATABASE "${scratchDatabase}"`);
    await client.end();

    const scratchUrl = new URL(admin.toString());

    scratchUrl.pathname = `/${scratchDatabase}`;

    console.log('');
    console.log(`--- database: scratch database ${scratchDatabase} created ---`);

    const withDatabase = scrubbed({ DATABASE_URL: scratchUrl.toString() });

    const database = [
      // Prisma's exact wording. An earlier draft read
      // /migrations? (have been )?applied/ and would have FAILED on a
      // successful deploy, because the string is "migration(s) have been
      // applied" and "(s)" sits where that pattern wanted a space. A positive
      // signal that does not match the success case is worse than none: it
      // turns every green run red and teaches the next person to widen it.
      [
        'pnpm db:deploy',
        'pnpm',
        ['db:deploy'],
        /migration\(s\) have been applied|No pending migrations to apply|Database schema is up to date/i,
      ],
      ['pnpm test:db', 'pnpm', ['test:db'], /Test Files\s+\d+ passed/],
    ];

    for (const [label, command, args, expect] of database) {
      const result = run(label, command, args, there, expect, withDatabase);

      if (!result.ok) {
        console.error('');
        console.error(`GATE:CLONE FAILED - ${result.why}`);
        console.error('');
        console.error(`The scratch database was ${scratchDatabase}, migrated from empty by`);
        console.error('the clone itself. A failure here is a migration or a suite that');
        console.error('only works against a database somebody prepared by hand.');
        await dropScratch();
        process.exit(1);
      }
    }
  }

  console.log('');
  console.log('GATE:CLONE PASSED');
  // R223: said AFTER the pass, because it is about what CI will do with a push
  // this gate has just approved - not about whether the work is sound.
  console.log(describeReadiness(ciReadiness()));
  console.log(`  commit  ${head}`);
  console.log(`  clone   ${clone} (removed)`);
  console.log(`  ran     install, typecheck, lint, test, build, size${local === null ? '' : ', db:deploy, test:db'}`);
  console.log(`  skipped ${CANNOT_RUN_HERE.map(([step]) => step).join(', ')}${local === null ? ', db:deploy, test:db' : ''}`);
} finally {
  await dropScratch();
  rmSync(clone, { recursive: true, force: true });
}
